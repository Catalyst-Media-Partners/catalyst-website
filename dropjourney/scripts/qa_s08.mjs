import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(new URL('..',import.meta.url).pathname),read=p=>readFile(path.join(root,p),'utf8');
const buyer=await read('dist/dropjourneytest/buyers/index.html'),wizard=await read('dist/dropjourneytest/buyers/apply/index.html');
const canonical=await read('../src/sections/buyers.html');
assert.equal((buyer.match(/class="dj-buyer-area"/g)||[]).length,4,'Four original buyer groups');
for(const m of canonical.matchAll(/<h3>(.*?)<\/h3>/g))assert.ok(buyer.includes(m[1]),'Lost buyer group '+m[1]);
for(const m of canonical.matchAll(/<article class="detail-box[^>]*>[\s\S]*?<p>([\s\S]*?)<\/p>/g))assert.ok(buyer.includes(m[1]),'Lost buyer source detail');
for(const ref of ['#buying','#exhibiting','/dropjourneytest/buyers/apply/','/dropjourneytest/opportunities/'])assert.ok(buyer.includes(`href="${ref}"`),'Buyer page lacks '+ref);
assert.match(buyer,/interactive demonstration/,'Buyer page requires transparent intake status');
assert.match(wizard,/id="buyer-form"/,'Wizard DOM missing');
assert.equal((wizard.match(/class="buyer-step/g)||[]).length,6,'Six guided steps');
for(const id of ['buyer-forward','buyer-prev','buyer-copy','buyer-meter','buyer-error','buyer-review','buyer-status'])assert.ok(wizard.includes(`id="${id}"`),'Wizard control missing '+id);
assert.match(wizard,/role="alert"/,'Accessible errors');
assert.match(wizard,/role="progressbar"/,'Accessible progress');
assert.match(wizard,/not submitted or stored/i,'Clear non-submitting status');
assert.doesNotMatch(wizard,/<form\b|action="\/|fetch\(/i,'Wizard must not have live form or network handler');
const js=await read('src/site.js');
assert.match(js,/navigator\.clipboard\.writeText/,'Explicit copy action retained');
assert.match(js,/field\('email'\)\.checkValidity\(\)/,'Email validation retained');
assert.doesNotMatch(js,/localStorage|sessionStorage|sendBeacon\(/,'Do not persist buyer information locally or transmit');
console.log('PASS DJ-S08: two-sided Hosted Buyer path, accessible six-step non-submitting qualification, preserved original groups');