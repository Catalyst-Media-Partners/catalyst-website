import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFile(path.join(root,p),'utf8');
const options=await read('dist/dropjourneytest/opportunities/index.html');
const css=await read('src/finish.css');
const renderer=await read('src/s09-pages.mjs');
const build=await read('build.mjs');
const container=options.slice(options.indexOf('<section class="section dj-offers-page"'),options.indexOf('</main>'));
assert.match(container,/class="dj-offers-visual"/,'Keep approved photograph');
assert.match(container,/class="dj-offers-booking"/,'Keep actual published price information');
assert.match(container,/class="dj-sponsor-spotlight"/,'Sponsor must have a direct visible section');
assert.match(container,/id="sponsorship"/,'Sponsor anchor must survive');
assert.match(container,/href="#sponsorship"/,'Hero sponsorship route must target live section');
assert.match(container,/<details class="dj-more-pathways"><summary>/,'Secondary options must be progressively disclosed');
const bookAt=container.indexOf('class="dj-offers-booking"'),sponsorAt=container.indexOf('class="dj-sponsor-spotlight"'),moreAt=container.indexOf('class="dj-more-pathways"');
assert.ok(bookAt>=0&&bookAt<sponsorAt&&sponsorAt<moreAt,'Decision order must be booth terms, sponsor, optional secondary paths');
assert.equal((container.match(/class="dj-offer"/g)||[]).length,6,'Never drop any of the six authorized commercial offerings');
assert.doesNotMatch(options,/class="dj-related"/,'Do not append duplicate generic booth call to action');
assert.match(options,/href="https:\/\/infused\.show\/go\/booth\?/,'First-party purchase handoff must remain');
assert.match(options,/10×10 inline booths start at \$3,000/,'Source booth price not preserved');
assert.match(options,/Availability and pricing may change/,'Commercial qualification must remain');
assert.match(css,/\.dj-offers-page \.dj-offers-visual img\{[^}]*max-height:310px/,'Photo cap too large');
assert.match(css,/max-height:170px;aspect-ratio:16\/8/,'Mobile photo cap too large');
assert.match(css,/\.dj-more-pathways summary:focus-visible/,'Native details accessible keyboard focus');
assert.match(renderer,/secondary\.length!==5/,'Five additional offers must remain');
assert.match(build,/route\.id==='opportunities'\?'':related\(route\)/,'Generic duplicate related CTA not removed');
assert.doesNotMatch(options,/<form\b/i,'Preview must not introduce submission');
console.log('PASS DJ-U2: capped photo, booth terms before five optional routes, sponsor deep-link, no redundant related CTA');
